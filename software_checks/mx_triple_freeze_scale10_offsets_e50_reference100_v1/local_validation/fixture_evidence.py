"""Produce explicit synthetic reference pins from genuinely executed fixtures."""
from __future__ import annotations
import json
from pathlib import Path
import shutil
import sys

sys.dont_write_bytecode = True


def read_json(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def write_json(path, value):
    Path(path).write_text(json.dumps(value, indent=2, allow_nan=False) + '\n', encoding='utf-8')


def prepare_reference_directories(r, fixtures, output):
    fixtures, output = Path(fixtures).resolve(), Path(output).resolve()
    output.mkdir(parents=True, exist_ok=False)
    info = read_json(fixtures / 'fixture.json')
    dynamic_run = Path(info['dynamic100_directory'])
    pilot_run = Path(info['frozen_pilot55_directory'])
    pilot_dir, dynamic_dir = output / 'pilot_reference', output / 'dynamic_reference'
    pilot_dir.mkdir(); dynamic_dir.mkdir()
    # The feedback bundle is generated by the actual, unchanged pilot exporter.
    from zipfile import ZipFile
    with ZipFile(pilot_run / 'feedback_bundle.zip') as archive:
        for entry in archive.infolist():
            path = (pilot_dir / entry.filename).resolve()
            assert path.is_relative_to(pilot_dir) and not entry.is_dir()
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(archive.read(entry))
    state = r.core.load_verified(pilot_run / 'checkpoints/epoch_00055.pt')
    history = read_json(pilot_dir / 'history.json')
    contract = state['contract']
    write_json(pilot_dir / 'parent_contract55.json', contract)
    pilot_meta = dict(schema='mx-freeze100-pilot55-reference-v1',
        source_feedback_filename='SYNTHETIC_FREEZE_PILOT55_ONLY',
        source_feedback_sha256=r.core.file_sha256(pilot_run / 'feedback_bundle.zip'),
        source_run_directory=str(pilot_run), source_contract_sha256=r.core.json_digest(contract),
        parent_epoch=55, parent_model_sha256=r.s.legacy.state_digest(state['model']),
        parent_optimizer_steps=110,
        parent_checkpoint_sha256=r.core.file_sha256(pilot_run / 'checkpoints/epoch_00055.pt'),
        parent_checkpoint_trace_sha256=r.core.json_digest(state['trace']),
        source_history_sha256=r.core.file_sha256(pilot_dir / 'history.json'),
        freeze_anchor_epoch=50, freeze_anchor_model_sha256=history['initial_model_sha256'],
        synthetic_fixture_only=True,
        files_sha256={path.relative_to(pilot_dir).as_posix():r.core.file_sha256(path)
                      for path in sorted(pilot_dir.rglob('*')) if path.is_file()})
    write_json(pilot_dir / 'REFERENCE.json', pilot_meta)
    names = ['parent_contract.json', 'run_report.json', 'epoch_metrics.csv', 'epoch_times.csv',
             'scale_epoch_metrics.csv', 'checkpoint_selection.json', 'selected_metrics.csv',
             'training_summary.json']
    for name in names:
        shutil.copyfile(dynamic_run / name, dynamic_dir / name)
    original_contract = read_json(dynamic_dir / 'parent_contract.json')
    dynamic_meta = dict(schema='mx-freeze100-dynamic-reference-v1',
        source_run_directory=str(dynamic_run), source_contract_sha256=r.core.json_digest(original_contract),
        source_history_sha256=r.core.file_sha256(dynamic_run / 'history.json'),
        history_json_external_at_packaging=True,
        history_source_policy='SYNTHETIC ONLY: read original actually executed dynamic100 history',
        files_sha256={path.relative_to(dynamic_dir).as_posix():r.core.file_sha256(path)
                      for path in sorted(dynamic_dir.rglob('*')) if path.is_file()},
        synthetic_fixture_only=True)
    dynamic_meta['files_sha256']['history.json'] = dynamic_meta['source_history_sha256']
    write_json(dynamic_dir / 'REFERENCE.json', dynamic_meta)
    return dict(pilot_dir=pilot_dir, dynamic_dir=dynamic_dir, dynamic_run=dynamic_run,
        pilot_run=pilot_run, parent_checkpoint55=pilot_run / 'checkpoints/epoch_00055.pt',
        expected_pilot_sha=r.core.file_sha256(pilot_dir / 'REFERENCE.json'),
        expected_dynamic_sha=r.core.file_sha256(dynamic_dir / 'REFERENCE.json'), fixture_info=info)


if __name__ == '__main__':
    if len(sys.argv) != 4:
        raise SystemExit('Usage: fixture_evidence.py PACKAGE FIXTURES OUTPUT')
    package, fixtures, output = map(lambda p:Path(p).resolve(), sys.argv[1:])
    sys.path.insert(0, str(package))
    import continuation_core as runtime
    result = prepare_reference_directories(runtime, fixtures, output)
    result = {key:str(value) if isinstance(value, Path) else value for key, value in result.items()}
    write_json(output / 'reference_paths.json', result)
    runtime.load_evidence(Path(result['dynamic_run']), Path(result['pilot_dir']),
        Path(result['dynamic_dir']), result['expected_pilot_sha'], result['expected_dynamic_sha'])
    print(json.dumps(dict(status='PASS', reference_paths=str(output / 'reference_paths.json'))))

